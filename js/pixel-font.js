function compileGlyph(pattern, fixedWidth) {
  const rows = pattern.split(" ");
  const painted = rows.filter(row => row.includes("#"));
  const left = fixedWidth ? 0 : Math.min(...painted.map(row => row.indexOf("#")));
  const right = fixedWidth ? 4 : Math.max(...painted.map(row => row.lastIndexOf("#")));
  const runs = [];
  for (const [y, row] of rows.entries()) {
    for (let column = left; column <= right; column++) {
      if (row[column] !== "#") continue;
      const start = column;
      while (row[column + 1] === "#") column++;
      runs.push({ x: start - left, y, width: column - start + 1 });
    }
  }
  return { width: right - left + 1, runs };
}

const glyphs = Object.fromEntries(Object.entries(patterns).map(([character, pattern]) =>
  [character, compileGlyph(pattern, /^[0-9]$/.test(character))]));
for (const [character, alias] of Object.entries(aliases)) glyphs[character] = glyphs[alias];
glyphs[" "] = { width: 3, runs: [] };

function glyphFor(character) {
  return glyphs[character] ?? glyphs["?"];
}

export function textWidth(text) {
  let width = 0;
  for (const character of text) width += glyphFor(character).width + 1;
  return Math.max(0, width - 1);
}

export function label(ctx, text, x, y, color) {
  let left = Math.round(x) - Math.floor(textWidth(text) / 2);
  const top = Math.round(y);
  ctx.fillStyle = color;
  for (const character of text) {
    const glyph = glyphFor(character);
    for (const run of glyph.runs) ctx.fillRect(left + run.x, top + run.y, run.width, 1);
    left += glyph.width + 1;
  }
}
